/** Render a delivery note / GRN (as generated by generateTradeDeliveryNote) to a PDF Buffer. */
export async function renderDeliveryNotePdf(deliveryNote) {
  const doc = new PDFDocument({ size: 'LETTER', margin: PAGE_MARGIN, bufferPages: true });

  drawHeader(doc, { badge: 'DELIVERY NOTE & GRN', title: `Delivery Note ${deliveryNote.deliveryNoteNumber}`, accentColor: '#059669' });

  let y = drawTwoColumn(
    doc,
    145,
    [
      { label: 'Order', value: deliveryNote.orderNumber, bold: true },
      { label: 'Dispatch Date', value: deliveryNote.dispatchDate },
      { label: 'Security Seal', value: deliveryNote.sealNumber, bold: true },
    ],
    [
      { label: 'Deliver To', value: deliveryNote.customer.tradingName, bold: true },
      { label: 'Address', value: deliveryNote.customer.deliveryAddress?.addressLine || 'N/A' },
      { label: 'Driver', value: `${deliveryNote.logistics.driverName} (${deliveryNote.logistics.vehicleRegistration})` },
    ]
  );

  const columns = [
    { label: 'SKU / Product', x: PAGE_MARGIN, width: 260 },
    { label: 'Ordered', x: PAGE_MARGIN + 265, width: 90, align: 'center' },
    { label: 'Dispatched', x: PAGE_MARGIN + 360, width: 90, align: 'center' },
    { label: 'Received', x: PAGE_MARGIN + 455, width: 70, align: 'center' },
  ];
  const rowColumns = [
    { ...columns[0], value: (r) => `${r.name} (${r.sku})` },
    { ...columns[1], value: (r) => r.orderedQuantity },
    { ...columns[2], value: (r) => r.dispatchedQuantity },
    { ...columns[3], value: (r) => r.receivedQuantity },
  ];

  y = drawTableHeader(doc, y + 10, columns);
  for (const item of deliveryNote.items || []) {
    y = ensureRoom(doc, y, 24, columns, true);
    y = drawTableRow(doc, y, rowColumns, item);
  }

  y = ensureRoom(doc, y, 100, columns, false);
  y += 14;
  doc.fillColor(MUTED).font('Helvetica').fontSize(8).text(deliveryNote.notes || '', PAGE_MARGIN, y, { width: PAGE_WIDTH - PAGE_MARGIN * 2 });
  y += doc.heightOfString(deliveryNote.notes || '', { width: PAGE_WIDTH - PAGE_MARGIN * 2 }) + 50;

  doc.strokeColor(RULE).moveTo(PAGE_MARGIN, y).lineTo(PAGE_MARGIN + 200, y).stroke();
  doc.fillColor(MUTED).fontSize(8).text('Received in good condition — Signature', PAGE_MARGIN, y + 4);
  doc.strokeColor(RULE).moveTo(PAGE_MARGIN + 260, y).lineTo(PAGE_MARGIN + 460, y).stroke();
  doc.text('Date', PAGE_MARGIN + 260, y + 4);

  return toBuffer(doc);
}
